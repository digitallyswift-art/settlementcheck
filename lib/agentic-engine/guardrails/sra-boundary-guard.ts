export function auditRegulatoryAndAdversarialTraps(text: string): {
  isCompliant: boolean;
  violations: RegulatoryBoundaryViolation[];
} {
  const violations: RegulatoryBoundaryViolation[] = [];
  for (const check of REGULATORY_AUDIT_RULES) {
    if (check.regex.test(text)) {
      violations.push({
        rule: check.rule,
        regulator: check.regulator,
        detail: check.detail,
      });
    }
  }
  return {
    isCompliant: violations.length === 0,
    violations,
  };
}

export function sanitizeAdvicePhrasing(text: string): string {
  let sanitized = text;
  for (const [regex, replacement] of FORBIDDEN_REPLACEMENTS) {
    if (regex.test(sanitized)) {
      sanitized = sanitized.replace(regex, replacement);
    }
  }
  return sanitized;
}

export function enforceSraRegulatoryBoundary(text: string): { sanitizedText: string; isModified: boolean } {
  let sanitized = sanitizeAdvicePhrasing(text);
  let isModified = sanitized !== text;

  // Ensure disclaimer presence if it's a long report
  if (!sanitized.includes('Section 203(3)') && sanitized.length > 200) {
    sanitized += `\n\n---\n**SRA Regulatory Notice**: ${SRA_COMPLIANCE_DISCLAIMER}`;
    isModified = true;
  }

  return {
    sanitizedText: sanitized,
    isModified,
  };
}

/**
 * Taxonomizes a search query or dispute context into FINANCIAL_CALCULATION vs EMOTIONAL_DISPUTE
 * so statutory guardrails enforce either financial caps (£751 / £30,000) OR Section 203 ERA 1996
 * independent solicitor rights & employer fee coverage for non-redundancy hostile exits.
 */
export function classifyStatutoryRequirementCategory(
  queryOrContext: string
): 'FINANCIAL_CALCULATION' | 'EMOTIONAL_DISPUTE' {
  const q = queryOrContext.toLowerCase();
  const emotionalDisputeTriggers = [
    'constructive dismissal',
    'discrimination',
    'bullying',
    'harassment',
    'pressured',
    'withdraw',
    'do not sign',
    "don't sign",
    'sick leave',
    'pip',
    'performance improvement',
    'protected conversation',
    'without prejudice',
    'maternity',
    'whistleblowing',
  ];

  for (const trigger of emotionalDisputeTriggers) {
    if (q.includes(trigger)) {
      return 'EMOTIONAL_DISPUTE';
    }
  }

  return 'FINANCIAL_CALCULATION';
}

/**
 * Verifies intent-calibrated statutory tokens in generated snippets
 */
export function verifyIntentCalibratedStatutoryTokens(
  text: string,
  category: 'FINANCIAL_CALCULATION' | 'EMOTIONAL_DISPUTE',
  weeklyCapGB: number = 751
): { isValid: boolean; reason?: string } {
  const lower = text.toLowerCase();

  if (category === 'EMOTIONAL_DISPUTE') {
    const hasSection203OrRights =
      lower.includes('section 203') ||
      lower.includes('era 1996') ||
      lower.includes('acas') ||
      lower.includes('equality act') ||
      lower.includes('solicitor') ||
      text.includes(`£${weeklyCapGB}`) ||
      text.includes('£30,000');

    const hasEmployerFeeGuarantee =
      lower.includes('employer') &&
      (lower.includes('fee') ||
        lower.includes('cost') ||
        lower.includes('pays') ||
        lower.includes('covers') ||
        lower.includes('contribut'));

    if (!hasSection203OrRights || !hasEmployerFeeGuarantee) {
      return {
        isValid: false,
        reason:
          'Emotional/dispute query copy must reference statutory protections (Section 203 ERA 1996 / ACAS / solicitor) and customary employer legal fee contribution.',
      };
    }
    return { isValid: true };
  }

  // Default: FINANCIAL_CALCULATION requires statutory financial caps (£751 or £30,000)
  if (!text.includes(`£${weeklyCapGB}`) && !text.includes('£30,000')) {
    return {
      isValid: false,
      reason: `Financial calculation copy missing required statutory figures (£${weeklyCapGB} or £30,000)`,
    };
  }

  return { isValid: true };
}
